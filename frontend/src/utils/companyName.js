const stripStrayQuote = (name) => {
  const count = (name.match(/"/g) || []).length;
  if (count % 2 === 1 && name.endsWith('"')) {
    return name.slice(0, -1).trimEnd();
  }
  return name;
};

export const shortName = (name = "") => {
  const trimmed = stripStrayQuote(name.trim());
  const upper = trimmed.toUpperCase();

  for (const [full, abbr] of FORMS) {
    if (upper.startsWith(full)) {
      const rest = trimmed.slice(full.length).trim();
      return rest ? `${abbr} ${rest}` : trimmed;
    }
  }

  return trimmed;
};
